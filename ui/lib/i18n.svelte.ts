export function setLang(l: Lang) {
  lang.current = l;
  document.documentElement.lang = l;
}

export function getLang(): Lang {
  return lang.current;
}

export function t(k: Key | string): string {
  const d = dicts[lang.current] as Record<string, string>;
  return d[k] ?? (pl as Record<string, string>)[k] ?? k;
}

export function stemLabel(s: string | null | undefined): string {
  if (!s) return "";
  const k = "stem_" + s;
  const v = t(k);
  return v === k ? s : v;
}
